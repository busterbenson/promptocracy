// Keeps the moderator's engine summaries in step with the capability registry (src/engine/capabilities/index.js).
//   node scripts/sync-capabilities.mjs           rewrites the block between the capability markers in moderator/APPLY.md and moderator/BUILD.md
//   node scripts/sync-capabilities.mjs --check   exits 1 if either file is out of step (tests/capabilities.mjs runs this logic)
// Gremlin's rule check reads the same sentences straight from the registry (src/lib/rule-check.js ENGINE_FACTS).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { capabilitySentences } from "../src/engine/capabilities/index.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const FILES = ["moderator/APPLY.md", "moderator/BUILD.md"];
const START = "<!-- engine-capabilities:start (generated by scripts/sync-capabilities.mjs from src/engine/capabilities/; do not edit by hand) -->", END = "<!-- engine-capabilities:end -->";
/** The block a prompt file carries: one bullet per capability, the registry's own sentence. */
export const block = () => [START, "   Engine capabilities beyond the hooks above (each is a power rules have; a rule that needs one of these is NOT an engine gap):", ...capabilitySentences().map((s) => `   - ${s}`), `   ${END}`].join("\n");
/** The file's text with its capability block replaced by the current one; throws when the markers are missing. */
export function synced(text) {
  const a = text.indexOf(START), b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error("the capability markers are missing");
  return text.slice(0, a) + block() + text.slice(b + END.length);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let bad = 0;
  for (const f of FILES) {
    const p = join(ROOT, f), cur = readFileSync(p, "utf8"), next = synced(cur);
    if (next === cur) continue;
    if (check) { console.log(`${f} is out of step with src/engine/capabilities/ (run node scripts/sync-capabilities.mjs)`); bad++; } else { writeFileSync(p, next); console.log(`${f} updated`); }
  }
  process.exit(bad ? 1 : 0);
}
